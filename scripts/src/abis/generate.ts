// Generates scripts/src/abis/*.ts from forge artifacts in contracts/out/.
// Run: pnpm --dir scripts abis   (after `forge build` in contracts/)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, "../../../contracts/out");

// [forge artifact name, exported const name]
const TARGETS: [string, string][] = [
  ["PoolSwapTest", "poolSwapTestAbi"],
  ["ConfluenceHook", "confluenceHookAbi"],
  ["MockMUMB", "mockMumbAbi"],
  ["IPoolManager", "poolManagerAbi"],
  ["PoolPriceBandExtruction", "poolPriceBandExtructionAbi"],
  ["IAqua", "aquaAbi"],
];

for (const [name, exportName] of TARGETS) {
  const artifact = resolve(out, `${name}.sol`, `${name}.json`);
  let abi: unknown;
  try {
    abi = JSON.parse(readFileSync(artifact, "utf8")).abi;
  } catch (e) {
    console.error(`cannot read ${artifact}: run \`forge build\` in contracts/ first`);
    process.exit(1);
  }
  const file = resolve(here, `${name}.ts`);
  const body =
    `// GENERATED by src/abis/generate.ts from contracts/out/${name}.sol. Do not edit.\n` +
    `export const ${exportName} = ${JSON.stringify(abi, null, 2)} as const;\n`;
  writeFileSync(file, body);
  console.log(`wrote ${file}`);
}
